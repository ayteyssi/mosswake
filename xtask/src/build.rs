use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{ensure, Context, Result};
use image::imageops::{overlay, resize, FilterType};
use image::{ImageBuffer, Rgba, RgbaImage};
use mw_core::assets::{
    AnimationManifest, PixelPoint, PixelRect, PixelSize, SpriteDef, MANIFEST_FILE,
};
use serde::Serialize;

const GENERATOR: &str = "mosswake-build-assets-v1";
const REPORT_FILE: &str = "build-report.json";

#[derive(Debug, Serialize)]
pub struct BuildReport {
    generator: &'static str,
    scale: u32,
    pub frames: u64,
    pub source_rgba_bytes: u64,
    pub output_rgba_bytes: u64,
    sprites: BTreeMap<String, Crop>,
}

/// Source coordinates can be negative when transparent padding aligns the pivot.
#[derive(Debug, Clone, Copy, Serialize)]
struct Crop {
    x: i64,
    y: i64,
    w: u32,
    h: u32,
}

pub fn build_assets(source: &Path, output: &Path, scale: u32) -> Result<BuildReport> {
    ensure!((1..=64).contains(&scale), "scale must be in 1..=64");
    let source = source.canonicalize().context("resolve source directory")?;
    ensure!(
        !fs::symlink_metadata(output).is_ok_and(|m| m.file_type().is_symlink()),
        "output must not be a symlink"
    );
    let output = resolve_output(output)?;
    ensure!(
        !source.starts_with(&output) && !output.starts_with(&source),
        "source and output directories must be disjoint"
    );
    if output.exists() {
        let marker = fs::read(output.join(REPORT_FILE))
            .context("refusing to replace a directory not generated by this tool")?;
        let marker: serde_json::Value = serde_json::from_slice(&marker)?;
        ensure!(
            marker["generator"] == GENERATOR,
            "unrecognized output directory"
        );
    }
    let mut manifest = AnimationManifest::load(&source)?;
    let issues = manifest.validate(&source);
    ensure!(issues.is_empty(), "invalid source manifest: {issues:#?}");
    let parent = output.parent().context("output needs a parent directory")?;
    fs::create_dir_all(parent)?;
    // Generate and validate a fresh tree before replacing an earlier generated tree.
    let staging = tempfile::Builder::new()
        .prefix(".mosswake-assets-")
        .tempdir_in(parent)?;
    let generated = staging.path().join("new");
    fs::create_dir(&generated)?;
    let mut report = BuildReport {
        generator: GENERATOR,
        scale,
        frames: 0,
        source_rgba_bytes: 0,
        output_rgba_bytes: 0,
        sprites: BTreeMap::new(),
    };
    for (sprite_index, (id, sprite)) in manifest.sprites.iter_mut().enumerate() {
        let crop = sprite_crop(&source, sprite, scale).with_context(|| format!("sprite {id}"))?;
        let frame_size = PixelSize {
            w: crop.w / scale,
            h: crop.h / scale,
        };
        for (animation_index, animation) in sprite.animations.values_mut().enumerate() {
            // Indices avoid trusting sprite/animation names as filesystem paths. They are
            // stable because both maps are ordered; aliased source paths remain independent.
            let path = format!("frames/{sprite_index:03}/{animation_index:03}");
            fs::create_dir_all(generated.join(&path))?;
            for index in 0..animation.frames {
                let frame =
                    read_frame(&source.join(animation.frame_path(index)), sprite.frame_size)?;
                let mut canvas = RgbaImage::new(crop.w, crop.h);
                overlay(&mut canvas, &frame, -crop.x, -crop.y);
                let reduced = downsample(canvas, frame_size);
                reduced.save(generated.join(format!("{path}/{index:04}.png")))?;
                report.frames += 1;
                report.source_rgba_bytes += rgba_bytes(sprite.frame_size);
                report.output_rgba_bytes += rgba_bytes(frame_size);
            }
            animation.path = path;
        }
        sprite.pivot = PixelPoint {
            x: ((i64::from(sprite.pivot.x) - crop.x) / i64::from(scale)) as u32,
            y: ((i64::from(sprite.pivot.y) - crop.y) / i64::from(scale)) as u32,
        };
        sprite.hitbox = sprite.hitbox.map(|h| scaled_hitbox(h, crop, scale));
        sprite.frame_size = frame_size;
        sprite.pixels_per_tile /= scale as f32;
        report.sprites.insert(id.clone(), crop);
    }
    let issues = manifest.validate(&generated);
    ensure!(issues.is_empty(), "invalid generated manifest: {issues:#?}");
    write_json(&generated.join(MANIFEST_FILE), &manifest)?;
    write_json(&generated.join(REPORT_FILE), &report)?;

    let previous = staging.path().join("previous");
    if output.exists() {
        fs::rename(&output, &previous).context("move previous generated assets aside")?;
    }
    if let Err(error) = fs::rename(&generated, &output) {
        if previous.exists() {
            fs::rename(&previous, &output).context("restore previous generated assets")?;
        }
        return Err(error).context("install generated assets");
    }
    Ok(report)
}

fn rgba_bytes(size: PixelSize) -> u64 {
    u64::from(size.w) * u64::from(size.h) * 4
}

fn read_frame(path: &Path, expected: PixelSize) -> Result<RgbaImage> {
    let frame = image::open(path)
        .with_context(|| format!("decode {}", path.display()))?
        .into_rgba8();
    ensure!(
        frame.dimensions() == (expected.w, expected.h),
        "frame size changed: {}",
        path.display()
    );
    Ok(frame)
}

fn sprite_crop(root: &Path, sprite: &SpriteDef, scale: u32) -> Result<Crop> {
    let (px, py) = (i64::from(sprite.pivot.x), i64::from(sprite.pivot.y));
    let (mut left, mut top, mut right, mut bottom) = (px, py, px, py);
    if let Some(h) = sprite.hitbox {
        left = left.min(i64::from(h.x));
        top = top.min(i64::from(h.y));
        right = right.max(i64::from(h.x) + i64::from(h.w));
        bottom = bottom.max(i64::from(h.y) + i64::from(h.h));
    }
    // v1 has a shared frame layout for a sprite, so combine the opaque unions of all
    // animations. Keep pivots/hitboxes even when they extend beyond painted pixels.
    for animation in sprite.animations.values() {
        for index in 0..animation.frames {
            let frame = read_frame(&root.join(animation.frame_path(index)), sprite.frame_size)?;
            for (x, y, _) in frame.enumerate_pixels().filter(|(_, _, p)| p[3] != 0) {
                left = left.min(i64::from(x));
                top = top.min(i64::from(y));
                right = right.max(i64::from(x) + 1);
                bottom = bottom.max(i64::from(y) + 1);
            }
        }
    }
    let factor = i64::from(scale);
    let ceil = |n: i64| (n + factor - 1) / factor;
    left = px - ceil(px - left) * factor;
    top = py - ceil(py - top) * factor;
    Ok(Crop {
        x: left,
        y: top,
        w: u32::try_from(ceil((right - left).max(1)) * factor)?,
        h: u32::try_from(ceil((bottom - top).max(1)) * factor)?,
    })
}

fn scaled_hitbox(h: PixelRect, crop: Crop, scale: u32) -> PixelRect {
    let factor = i64::from(scale);
    let left = (i64::from(h.x) - crop.x) / factor;
    let top = (i64::from(h.y) - crop.y) / factor;
    let right = (i64::from(h.x) + i64::from(h.w) - crop.x + factor - 1) / factor;
    let bottom = (i64::from(h.y) + i64::from(h.h) - crop.y + factor - 1) / factor;
    PixelRect {
        x: left as u32,
        y: top as u32,
        w: (right - left) as u32,
        h: (bottom - top) as u32,
    }
}

fn downsample(canvas: RgbaImage, size: PixelSize) -> RgbaImage {
    // Interpolate premultiplied colors so transparent black does not darken the edges.
    let premultiplied: ImageBuffer<Rgba<f32>, Vec<f32>> =
        ImageBuffer::from_fn(canvas.width(), canvas.height(), |x, y| {
            let p = canvas.get_pixel(x, y);
            let a = f32::from(p[3]) / 255.0;
            Rgba([
                f32::from(p[0]) / 255.0 * a,
                f32::from(p[1]) / 255.0 * a,
                f32::from(p[2]) / 255.0 * a,
                a,
            ])
        });
    let reduced = resize(&premultiplied, size.w, size.h, FilterType::Lanczos3);
    ImageBuffer::from_fn(size.w, size.h, |x, y| {
        let p = reduced.get_pixel(x, y);
        let a = p[3].clamp(0.0, 1.0);
        let color = |i: usize| {
            if a > 0.0 {
                (p[i] / a).clamp(0.0, 1.0)
            } else {
                0.0
            }
        };
        Rgba([
            (color(0) * 255.0).round() as u8,
            (color(1) * 255.0).round() as u8,
            (color(2) * 255.0).round() as u8,
            (a * 255.0).round() as u8,
        ])
    })
}

fn write_json(path: &Path, value: &impl Serialize) -> Result<()> {
    let mut json = serde_json::to_string_pretty(value)?;
    json.push('\n');
    fs::write(path, json).with_context(|| format!("write {}", path.display()))
}

/// Canonicalize through the nearest existing ancestor without creating directories first.
fn resolve_output(path: &Path) -> Result<PathBuf> {
    let absolute = if path.is_absolute() {
        path.to_path_buf()
    } else {
        std::env::current_dir()?.join(path)
    };
    let mut ancestor = absolute.as_path();
    let mut suffix = Vec::new();
    while !ancestor.exists() {
        suffix.push(ancestor.file_name().context("invalid output path")?);
        ancestor = ancestor.parent().context("invalid output parent")?;
    }
    let mut resolved = ancestor.canonicalize()?;
    for name in suffix.into_iter().rev() {
        resolved.push(name);
    }
    Ok(resolved)
}

